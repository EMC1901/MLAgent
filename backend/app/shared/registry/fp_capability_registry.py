"""
Feature Preprocessing Capability Registry.

Defines the 12 core preprocessing capability groups that the Feature Preprocessing
LLM can select from when generating a PreprocessingPlan.

All operations reference capabilities defined here — no unregistered operations
may be executed. Each capability includes parameter schemas, fit scope, risk notes,
and fallback mappings.
"""
from typing import List, Optional, Dict, Any
from pydantic import BaseModel


class FPCapabilitySpec(BaseModel):
    capability_id: str
    display_name: str
    capability_group: str  # one of the 12 groups
    operation_type: str  # imputation | analysis | filtering | scaling | transformation | redundancy_filter | leakage_detection | feature_selection | group_policy | dimensionality_reduction | lineage | artifact_tracking
    status: str  # available | planned | disabled | experimental
    supported_feature_types: List[str] = ["numeric", "categorical", "boolean"]
    supported_feature_groups: List[str] = ["composition", "structure", "descriptor", "metadata", "generated"]
    requires_target: bool = False
    fit_scope: str = "dataset_profile_only"  # dataset_profile_only | train_only | fold_only
    allowed_pipeline_positions: List[str] = []
    parameters_schema: dict = {}
    default_parameters: dict = {}
    risk_notes: List[str] = []
    fallback_capability_ids: List[str] = []
    version: str = "1.0.0"


