# Fast lookup
FP_CAPABILITY_BY_ID: Dict[str, FPCapabilitySpec] = {
    c.capability_id: c for c in PREPROCESSING_CAPABILITIES
}


def get_available_fp_capabilities(
    capability_group: Optional[str] = None,
    operation_type: Optional[str] = None,
) -> List[FPCapabilitySpec]:
    """Return FP capabilities with status='available', optionally filtered by group or type."""
    result = [c for c in PREPROCESSING_CAPABILITIES if c.status == "available"]
    if capability_group:
        result = [c for c in result if c.capability_group == capability_group]
    if operation_type:
        result = [c for c in result if c.operation_type == operation_type]
    return result


def get_all_fp_capabilities(status: Optional[str] = None) -> List[FPCapabilitySpec]:
    """Return all FP capabilities, optionally filtered by status."""
    if status:
        return [c for c in PREPROCESSING_CAPABILITIES if c.status == status]
    return list(PREPROCESSING_CAPABILITIES)


def get_fp_capability_by_id(capability_id: str) -> Optional[FPCapabilitySpec]:
    """Look up a single FP capability by its ID."""
    return FP_CAPABILITY_BY_ID.get(capability_id)


def get_registry_snapshot_fp() -> Dict[str, Any]:
    """Return a lightweight snapshot for persistence."""
    import datetime
    return {
        "snapshot_version": "1.0.0",
        "created_at": datetime.datetime.now().isoformat(),
        "total_capabilities": len(PREPROCESSING_CAPABILITIES),
        "available_count": len([c for c in PREPROCESSING_CAPABILITIES if c.status == "available"]),
        "capability_groups": {
            k: len([c for c in PREPROCESSING_CAPABILITIES if c.capability_group == k and c.status == "available"])
            for k in CAPABILITY_GROUPS
        },
        "capabilities": [c.model_dump() for c in PREPROCESSING_CAPABILITIES],
    }
