from typing import Dict, Any, List
from app.modules.result_diagnosis.schemas import EvidenceItem, EvidenceSummary
from app.modules.result_diagnosis.enums import EvidenceType


def extract_evidence(di_input: Dict[str, Any], optional_contexts: Dict[str, Any]) -> EvidenceSummary:
    summary = EvidenceSummary()

    # Metric evidence
    metric_summary = di_input.get("metric_summary") or {}
    if metric_summary:
        summary.metric_evidence.append(EvidenceItem(
            evidence_type=EvidenceType.METRIC,
            source_module="metric_evaluation",
            source_field="best_metric_value",
            value=metric_summary.get("best_metric_value"),
            interpretation=f"Best primary metric value across all models."
        ))
        summary.metric_evidence.append(EvidenceItem(
            evidence_type=EvidenceType.METRIC,
            source_module="metric_evaluation",
            source_field="mean_metric_value",
            value=metric_summary.get("mean_metric_value"),
            interpretation=f"Mean primary metric value across {metric_summary.get('n_trials_contributing', 0)} trials."
        ))
        if metric_summary.get("std_metric_value") is not None:
            summary.metric_evidence.append(EvidenceItem(
                evidence_type=EvidenceType.METRIC,
                source_module="metric_evaluation",
                source_field="std_metric_value",
                value=metric_summary["std_metric_value"],
                interpretation=f"Standard deviation of primary metric across trials."
            ))

    # Baseline evidence
    baseline = di_input.get("baseline_comparison") or {}
    if baseline:
        summary.baseline_evidence.append(EvidenceItem(
            evidence_type=EvidenceType.BASELINE,
            source_module="metric_evaluation",
            source_field="candidate_beats_baseline",
            value=baseline.get("candidate_beats_baseline"),
            interpretation="Whether the best candidate model outperforms the best baseline."
        ))
        if baseline.get("absolute_improvement") is not None:
            direction = di_input.get("metric_direction", "minimize")
            improved = (
                (direction == "minimize" and baseline["absolute_improvement"] < 0)
                or (direction == "maximize" and baseline["absolute_improvement"] > 0)
            )
            summary.baseline_evidence.append(EvidenceItem(
                evidence_type=EvidenceType.BASELINE,
                source_module="metric_evaluation",
                source_field="absolute_improvement",
                value=baseline["absolute_improvement"],
                interpretation=f"Absolute improvement over best baseline (improved={'yes' if improved else 'no'})."
            ))

    # Fold stability evidence
    stability = di_input.get("stability_summary") or {}
    if stability:
        summary.fold_stability_evidence.append(EvidenceItem(
            evidence_type=EvidenceType.FOLD_STABILITY,
            source_module="metric_evaluation",
            source_field="mean_cv_std",
            value=stability.get("mean_cv_std"),
            interpretation=f"Mean cross-validation standard deviation across trials."
        ))
        summary.fold_stability_evidence.append(EvidenceItem(
            evidence_type=EvidenceType.FOLD_STABILITY,
            source_module="metric_evaluation",
            source_field="max_cv_std",
            value=stability.get("max_cv_std"),
            interpretation=f"Maximum cross-validation standard deviation."
        ))

    # Dataset evidence
    ds_ctx = optional_contexts.get("dataset_profile") or {}
    if ds_ctx:
        profile = ds_ctx.get("profile_json") or ds_ctx
        summary.dataset_evidence.append(EvidenceItem(
            evidence_type=EvidenceType.DATA_PROFILE,
            source_module="dataset_profile",
            source_field="n_samples",
            value=profile.get("n_samples") or profile.get("row_count"),
            interpretation=f"Number of samples in the dataset."
        ))

    # Feature evidence
    fe_ctx = optional_contexts.get("feature_engineering") or {}
    fp_ctx = optional_contexts.get("feature_preprocessing") or {}
    if fe_ctx:
        fe_json = fe_ctx.get("feature_json") or fe_ctx
        n_features = fe_json.get("n_features_generated") or fe_json.get("n_features")
        summary.feature_evidence.append(EvidenceItem(
            evidence_type=EvidenceType.FEATURE_PROFILE,
            source_module="feature_engineering",
            source_field="n_features",
            value=n_features,
            interpretation=f"Number of features generated by feature engineering."
        ))
    if fp_ctx:
        fp_json = fp_ctx.get("preprocessing_json") or fp_ctx
        n_final = fp_json.get("n_final_features")
        n_dropped = fp_json.get("n_features_dropped")
        summary.feature_evidence.append(EvidenceItem(
            evidence_type=EvidenceType.FEATURE_PROFILE,
            source_module="feature_preprocessing",
            source_field="n_final_features",
            value=n_final,
            interpretation=f"Number of final features after preprocessing."
        ))
        if n_dropped is not None:
            summary.feature_evidence.append(EvidenceItem(
                evidence_type=EvidenceType.FEATURE_PROFILE,
                source_module="feature_preprocessing",
                source_field="n_features_dropped",
                value=n_dropped,
                interpretation=f"Number of features dropped during preprocessing."
            ))

    # Pipeline evidence
    pe_ctx = optional_contexts.get("pipeline_execution") or {}
    if pe_ctx:
        exec_json = pe_ctx.get("execution_json") or pe_ctx
        n_trials = exec_json.get("n_trials_executed") or exec_json.get("n_trials_total")
        n_failed = exec_json.get("n_trials_failed", 0)
        summary.pipeline_evidence.append(EvidenceItem(
            evidence_type=EvidenceType.PIPELINE_LOG,
            source_module="pipeline_execution",
            source_field="n_trials",
            value={"n_trials": n_trials, "n_failed": n_failed},
            interpretation=f"Pipeline execution: {n_trials} trials, {n_failed} failed."
        ))

    return summary
